CREATE TABLE REPRESENTATIVE (
    REPRESENTATIVE_ID INT IDENTITY(1,1) ,
    FULL_NAME VARCHAR(100) NOT NULL,
    PHONE VARCHAR(20),
    EMAIL VARCHAR(100),
    LICENSE_NUMBER VARCHAR(50),

    CONSTRAINT PK_REPRESENTATIVE PRIMARY KEY (REPRESENTATIVE_ID)
);
GO



CREATE TABLE CLIENT (
    CLIENT_ID INT IDENTITY(1,1),
    FULL_NAME VARCHAR(100) NOT NULL,
    CLIENT_CONTACT_PREFERENCE VARCHAR(100),
    CLIENT_PHONE VARCHAR(20),
    CLIENT_EMAIL VARCHAR(100),

    CONSTRAINT PK_CLIENT PRIMARY KEY (CLIENT_ID)
);
GO


CREATE TABLE PROPERTY (
    PROPERTY_ID INT IDENTITY(1,1),
    REPRESENTATIVE_ID INT,
    STYLE VARCHAR(100) NOT NULL,
    LATITUDE FLOAT NOT NULL,
    LONGITUDE FLOAT NOT NULL,
    ADDRESS VARCHAR(255) NOT NULL,
    MARKET_VALUE DECIMAL(12,2) NOT NULL,
    PROPERTY_STATUS VARCHAR(100),

    CONSTRAINT PK_PROPERTY PRIMARY KEY (PROPERTY_ID)
);
GO



CREATE TABLE TOUR (
    TOUR_ID INT IDENTITY(1,1) NOT NULL,
    CLIENT_ID INT,
    PROPERTY_ID INT,
    REPRESENTATIVE_ID INT,
    TOUR_DATE DATE,
    TOUR_TIME TIME,

    CONSTRAINT PK_TOUR PRIMARY KEY (TOUR_ID)
);
GO


CREATE TABLE AGREEMENT (
    AGREE_ID INT IDENTITY(1,1) NOT NULL,
    CLIENT_ID INT,
    PROPERTY_ID INT,
    FINAL_PRICE DECIMAL(12,2),
    EFFECTIVE_DATE DATE,

    CONSTRAINT PK_AGREEMENT PRIMARY KEY (AGREE_ID)
);
GO


CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID INT IDENTITY(1,1) NOT NULL,
    CLIENT_ID INT,
    TOUR_ID INT,
    REPRESENTATIVE_ID INT,
    TRANSACTION_AMOUNT DECIMAL(12,2),
    TRANSACTION_STATUS VARCHAR(20),
    TRANSACTION_DATE DATETIME,

    CONSTRAINT PK_TRANSACTIONS PRIMARY KEY (TRANSACTION_ID)
);
GO



